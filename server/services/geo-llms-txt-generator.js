// ACMS GEO — llms.txt v2 规范实现（v0.1 — Phase 0 D3）
// 路径：server/services/geo-llms-txt-generator.js
//
// 规范来源：Jeremy Howard / Answer.AI 提出的 llms.txt 规范（v2）
//   https://llmstxt.org （概念站）
//   https://github.com/AnswerDotAI/llms-txt （示例仓库）
//
// 规范核心结构（v2）：
//   # Title             ← 必填，页面 <title>
//   > Summary           ← 可选，<meta name="description">
//   ## Section Name     ← 每个 H1/H2 一个 section
//   [section content in markdown]
//   ## Optional         ← 可选，剩余内容（次要）
//
// 设计要点：
//   - 用 ACMS proxyFetch 抓 HTML（复用现有代理基础设施 + 反爬）
//   - 用 cheerio 解析（已装 1.2.0）
//   - 输出文件到 data/geo/llms-txt/<domain>.txt（已建目录）
//   - 失败返回 {ok:false, error, message} 不抛异常（跟 D2 工具一致）

const cheerio = require('cheerio');
const { proxyFetch } = require('./proxy-fetch');
const path = require('path');
const fs = require('fs').promises;

const TIMEOUT_MS = 30000;
const MAX_HTML_BYTES = 5 * 1024 * 1024; // 5MB 上限（防 OOM）
const OUTPUT_DIR = path.join(__dirname, '..', '..', 'data', 'geo', 'llms-txt');

// 通用 user-agent（部分站对默认 UA 反感爬）
const UA = 'Mozilla/5.0 (compatible; ACMS-GEO-Bot/0.1; +https://acms.ai)';

function domainFromUrl(url) {
  try {
    const u = new URL(url);
    return u.hostname.replace(/^www\./, '');
  } catch {
    return null;
  }
}

// 提取 title
function extractTitle($) {
  return (
    $('head > title').first().text().trim() ||
    $('meta[property="og:title"]').attr('content') ||
    $('h1').first().text().trim() ||
    domainFromUrl($('html').attr('lang') ? '' : '') ||
    'Untitled'
  );
}

// 提取 description（多种 fallback）
function extractSummary($) {
  return (
    $('meta[name="description"]').attr('content') ||
    $('meta[property="og:description"]').attr('content') ||
    $('meta[name="twitter:description"]').attr('content') ||
    ''
  ).trim();
}

// 主解析：把 HTML 转 llms.txt 文本
function parseHtmlToLlmsTxt(html, baseUrl) {
  const $ = cheerio.load(html);

  const title = extractTitle($);
  const summary = extractSummary($);

  // 收集所有 H1/H2 作为 section 边界
  // 策略：每个 H2 是一个 section；如果没有 H2，则每个 H1 是一个 section
  const sections = [];
  let currentSection = null;
  const safeTags = new Set(['p', 'ul', 'ol', 'li', 'code', 'pre', 'strong', 'em', 'a', 'br', 'blockquote', 'h3', 'h4', 'h5', 'h6']);

  // 找到主体内容区域（优先 article / main，否则 body）
  const root = $('article').first().length ? $('article').first() : ($('main').first().length ? $('main').first() : $('body'));

  root.children().each((_, el) => {
    const tag = el.tagName?.toLowerCase();
    if (tag === 'h1' || tag === 'h2') {
      if (currentSection) sections.push(currentSection);
      const text = $(el).text().trim();
      if (text) currentSection = { heading: text, level: tag, content: [] };
    } else if (currentSection && safeTags.has(tag)) {
      // 保留相对简单的 HTML → 转 markdown（轻量级转换）
      const html = $(el).html() || '';
      const md = htmlToMarkdown(html);
      if (md) currentSection.content.push(md);
    }
  });
  if (currentSection) sections.push(currentSection);

  // 如果一个 section 都没抓到，兜底用整个 body 的纯文本
  if (sections.length === 0) {
    const bodyText = root.text().trim().slice(0, 4000);
    if (bodyText) {
      sections.push({ heading: 'Content', level: 'h2', content: [bodyText] });
    }
  }

  // 组装输出
  const lines = [];
  lines.push(`# ${title}`);
  lines.push('');
  if (summary) {
    lines.push(`> ${summary}`);
    lines.push('');
  }
  if (baseUrl) {
    lines.push(`Source: ${baseUrl}`);
    lines.push('');
  }

  for (const sec of sections) {
    lines.push(`## ${sec.heading}`);
    lines.push('');
    for (const content of sec.content) {
      // 段落间空行
      if (content.trim()) {
        lines.push(content.trim());
        lines.push('');
      }
    }
  }

  // 可选：附元信息（生成时间）
  lines.push('## Optional');
  lines.push('');
  lines.push(`- Generated by ACMS GEO at ${new Date().toISOString()}`);
  lines.push(`- Source URL: ${baseUrl}`);
  lines.push(`- llms.txt spec: https://llmstxt.org`);
  lines.push('');

  return lines.join('\n');
}

// 极简 HTML → Markdown（够用就行的实现，不依赖外部库）
function htmlToMarkdown(html) {
  if (!html) return '';
  return html
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/(p|div|h[3-6])>/gi, '\n\n')
    .replace(/<li[^>]*>/gi, '- ')
    .replace(/<\/li>/gi, '\n')
    .replace(/<strong[^>]*>(.*?)<\/strong>/gi, '**$1**')
    .replace(/<b[^>]*>(.*?)<\/b>/gi, '**$1**')
    .replace(/<em[^>]*>(.*?)<\/em>/gi, '*$1*')
    .replace(/<i[^>]*>(.*?)<\/i>/gi, '*$1*')
    .replace(/<code[^>]*>(.*?)<\/code>/gi, '`$1`')
    .replace(/<a[^>]*href="([^"]+)"[^>]*>(.*?)<\/a>/gi, '[$2]($1)')
    .replace(/<[^>]+>/g, '') // 兜底去所有标签
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/[ \t]+/g, ' ')  // 合并多余空格
    .replace(/\n\s*\n\s*\n+/g, '\n\n') // 多空行合一
    .trim();
}

async function generate(url, options = {}) {
  const domain = domainFromUrl(url);
  if (!domain) {
    return { ok: false, error: 'INVALID_URL', message: `URL 格式无效: ${url}` };
  }

  // 1. 抓 HTML（用 ACMS proxyFetch，自动处理代理/直连）
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), TIMEOUT_MS);

  let response;
  try {
    response = await proxyFetch(url, {
      method: 'GET',
      headers: {
        'User-Agent': UA,
        'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8',
      },
      signal: controller.signal,
    });
  } catch (e) {
    clearTimeout(timeout);
    return {
      ok: false,
      error: e.name === 'AbortError' ? 'TIMEOUT' : 'FETCH_ERROR',
      message: e.message,
      url,
    };
  }
  clearTimeout(timeout);

  if (!response.ok) {
    return {
      ok: false,
      error: `HTTP_${response.status}`,
      message: `抓取 ${url} 失败: HTTP ${response.status}`,
      url,
      status: response.status,
    };
  }

  // 2. 读 HTML（限大小）
  const contentLength = parseInt(response.headers.get('content-length') || '0', 10);
  if (contentLength > MAX_HTML_BYTES) {
    return {
      ok: false,
      error: 'TOO_LARGE',
      message: `HTML 超过 ${MAX_HTML_BYTES / 1024 / 1024}MB 上限（content-length=${contentLength}）`,
      url,
    };
  }

  let html;
  try {
    html = await response.text();
  } catch (e) {
    return { ok: false, error: 'READ_ERROR', message: e.message, url };
  }

  if (html.length > MAX_HTML_BYTES) {
    return {
      ok: false,
      error: 'TOO_LARGE',
      message: `HTML 实际 ${html.length} 字节，超过 ${MAX_HTML_BYTES} 字节上限`,
      url,
    };
  }

  // 3. 解析 + 生成
  let llmsTxt;
  try {
    llmsTxt = parseHtmlToLlmsTxt(html, url);
  } catch (e) {
    return { ok: false, error: 'PARSE_ERROR', message: e.message, url };
  }

  // 4. 写文件（除非 caller 禁用）
  let savedPath = null;
  if (options.save !== false) {
    try {
      await fs.mkdir(OUTPUT_DIR, { recursive: true });
      const filename = options.filename || `${domain}.txt`;
      savedPath = path.join(OUTPUT_DIR, filename);
      await fs.writeFile(savedPath, llmsTxt, 'utf-8');
    } catch (e) {
      return {
        ok: true,
        url,
        domain,
        llms_txt: llmsTxt,
        saved: false,
        save_error: e.message,
      };
    }
  }

  return {
    ok: true,
    url,
    domain,
    llms_txt: llmsTxt,
    saved_path: savedPath,
    saved: !!savedPath,
    bytes: llmsTxt.length,
    generated_at: new Date().toISOString(),
  };
}

// 健康检查（不依赖外部 URL，验证模块自身 OK）
async function healthCheck() {
  try {
    const testHtml = '<html><head><title>Test</title><meta name="description" content="test desc"></head><body><h1>Hi</h1><p>Hello world</p></body></html>';
    const out = parseHtmlToLlmsTxt(testHtml, 'https://example.com');
    return {
      ok: true,
      cheerio: !!cheerio,
      proxy_fetch: !!proxyFetch,
      sample_output: out.slice(0, 300),
    };
  } catch (e) {
    return { ok: false, error: e.message };
  }
}

module.exports = {
  generate,
  healthCheck,
  parseHtmlToLlmsTxt,
  domainFromUrl,
  htmlToMarkdown,
  OUTPUT_DIR,
};